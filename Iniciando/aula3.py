# Aspas Simples (' ')
print('Danni')
print(1,'Danni "Silva"')
# Aspas Duplas  (" ")
print("Danni")
print(2,"Danni 'Silva'")
# Escape
print("Danni \"Silva\"") #caractere de Escape = \"
# r
print(r"Danni \"Silva\"") #Guarde esta regra: \ modifica a interpretação do caractere que vem depois dele em sequências de escape reconhecidas pelo Python. É por isso que \", \n e \\ produzem resultados diferentes.
